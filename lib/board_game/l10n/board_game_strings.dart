  static Map<String, String> _getStringsForLanguage(GameLanguage language) {
    switch (language) {
      case GameLanguage.korean:
        return _koreanStrings;
      case GameLanguage.japanese:
        return _japaneseStrings;
      case GameLanguage.english:
        return _englishStrings;
      case GameLanguage.chinese:
        return _chineseStrings;
    }
  }

  static String get(String key, {Map<String, String>? namedArgs}) {
    final strings = _getStringsForLanguage(currentLanguage);
    String value = strings[key] ?? _koreanStrings[key] ?? key;
    if (namedArgs != null) {
      namedArgs.forEach((argKey, argValue) {
        value = value.replaceAll('{$argKey}', argValue);
      });
    }
    return value;
  }
}

