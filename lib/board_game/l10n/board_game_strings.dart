  static String get(String key, {Map<String, String>? namedArgs}) {
    final strings = _getStringsForLanguage(currentLanguage);
    String value = strings[key] ?? _koreanStrings[key] ?? key;
    if (namedArgs != null) {
      namedArgs.forEach((argKey, argValue) {
        value = value.replaceAll('{$argKey}', argValue);
      });
    }
    return value;
  }
